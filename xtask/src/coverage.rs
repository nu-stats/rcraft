//! Generates `docs/coverage.md` from the catalog.

use std::fmt::Write as _;
use std::fs;

use rcraft_catalog::{Area, Entry, Status, ENTRIES};

use crate::{root, Result};

const PATH: &str = "docs/coverage.md";

pub fn run(check_only: bool) -> Result {
    let text = render(ENTRIES);
    let path = root().join(PATH);
    if check_only {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current.replace("\r\n", "\n") != text {
            return Err(format!("{PATH} is out of date; run `cargo xtask coverage`"));
        }
        println!("coverage: {PATH} is up to date");
    } else {
        fs::write(&path, text).map_err(|e| format!("could not write {PATH}: {e}"))?;
        println!("coverage: wrote {PATH}");
    }
    Ok(())
}

fn render(entries: &[Entry]) -> String {
    let count = |status: Status| entries.iter().filter(|e| e.status == status).count();

    let mut s = String::new();
    s.push_str("# Coverage inventory\n\n");
    s.push_str("Generated by `cargo xtask coverage` from `crates/catalog/src/lib.rs`. Do not edit by hand.\n\n");
    s.push_str(
        "An entry only counts as **verified** when the R its dialog generates, run in the \
         pinned R, gives the expected result.\n\n",
    );
    s.push_str("| Entries | Verified | Partial | Planned |\n|---:|---:|---:|---:|\n");
    let _ = writeln!(
        s,
        "| {} | {} | {} | {} |",
        entries.len(),
        count(Status::Verified),
        count(Status::Partial),
        count(Status::Planned),
    );

    let mut areas: Vec<Area> = entries.iter().map(|e| e.area).collect();
    areas.sort();
    areas.dedup();
    for area in areas {
        let _ = writeln!(s, "\n## {}\n", area.label());
        s.push_str("| Entry | Status |\n|---|---|\n");
        for e in entries.iter().filter(|e| e.area == area) {
            let _ = writeln!(s, "| {} | {} |", e.name, e.status.label());
        }
    }
    s
}
